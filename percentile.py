"""Percentile colouring for the top-five chart and stat table.

Each stat is compared with the rest of the eligible board, so a colour always
reflects the board itself, not an external standard. Green is the top third of
the board on that stat, yellow the middle third, red the bottom third.
"""

from scoring import split_complete

# Stats where a higher number is better. Every stat here comes from the CSV.
STATS = ["ppg", "rpg", "apg", "fg_pct", "three_pct", "bpm", "spg", "bpg"]

GREEN = "#3ddc84"
YELLOW = "#f5c542"
RED = "#ff5c5c"
GREY = "#5a5a70"


def _percentile(value, sorted_values):
    """Share of the board at or below this value, between 0.0 and 1.0."""
    at_or_below = sum(1 for v in sorted_values if v <= value)
    return at_or_below / len(sorted_values)


def colour_for(percentile):
    """Green top third, yellow middle third, red bottom third."""
    if percentile > 2 / 3:
        return GREEN
    if percentile > 1 / 3:
        return YELLOW
    return RED


def board_distributions(prospects):
    """Sorted values for each stat, using only prospects that have a value for it."""
    complete, _ = split_complete(prospects)
    dists = {}
    for stat in STATS:
        values = sorted(p[stat] for p in complete if p.get(stat) is not None)
        dists[stat] = values
    return dists


def stat_colours(player, dists):
    """For one player, return {stat: (percentile, colour)}. Missing stats get grey."""
    result = {}
    for stat in STATS:
        value = player.get(stat)
        values = dists.get(stat, [])
        if value is None or not values:
            result[stat] = (None, GREY)
            continue
        pct = _percentile(value, values)
        result[stat] = (pct, colour_for(pct))
    return result


def chart_colours(ranked_names, players, dists):
    """Bar colour for each name, keyed on the player's BPM percentile.

    BPM is the one production measure in the scoring, so it sets the bar colour.
    The full breakdown is in the stat table.
    """
    by_name = {p["name"]: p for p in players}
    colours = []
    for name in ranked_names:
        _, colour = stat_colours(by_name[name], dists)["bpm"]
        colours.append(colour)
    return colours


def stat_table_rows(ranked_names, players, dists):
    """One row per player, with each stat's value and its board colour."""
    by_name = {p["name"]: p for p in players}
    rows = []
    for name in ranked_names:
        player = by_name[name]
        colours = stat_colours(player, dists)
        cells = {}
        for stat in STATS:
            value = player.get(stat)
            _, colour = colours[stat]
            cells[stat] = (value, colour)
        rows.append((name, cells))
    return rows