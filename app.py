import html
import os

import pandas as pd
import streamlit as st

try:
    if "NEBIUS_API_KEY" in st.secrets:
        os.environ["NEBIUS_API_KEY"] = st.secrets["NEBIUS_API_KEY"]
except Exception:
    # No secrets file locally, so the key comes from .env instead.
    pass

from data_loader import load_prospects, validate
from explain import build_facts, explain
from pdf_export import build_report
from scoring import (
    BPM_CEILING, BPM_FLOOR, CLOSE_CALL_MARGIN, W_NEED, W_PROD, W_RANK,
    rank_prospects, recommend, split_complete,
)

DATA_PATH = "data/2027_nba_draft_big_board.csv"
POSITIONS = ["PG", "SG", "SF", "PF", "C"]

st.set_page_config(page_title="Draft Pick Evaluator", page_icon="🏀", layout="wide")

CSS = """
<style>
.stApp { background: radial-gradient(circle at top left, #1b1538 0%, #0b0b14 45%, #07070c 100%); }
section[data-testid="stSidebar"] { background: #0e0e18; border-right: 1px solid #1f1f33; }
.card { background: rgba(255,255,255,0.035); border: 1px solid rgba(255,255,255,0.08);
        border-radius: 18px; padding: 20px 22px; margin-bottom: 16px; }
.label { color: #8b8ba7; font-size: 0.75rem; text-transform: uppercase; letter-spacing: 0.08em; }
.big { color: #f4f4fb; font-size: 1.9rem; font-weight: 650; margin: 4px 0 6px; }
.sub { color: #a6a6c0; font-size: 0.95rem; }
.chip { display: inline-block; padding: 4px 12px; margin: 6px 6px 0 0; border-radius: 999px;
        font-size: 0.8rem; color: #cbbfff; background: rgba(124,92,255,0.18);
        border: 1px solid rgba(124,92,255,0.35); }
.alt { display: flex; justify-content: space-between; align-items: center;
       padding: 12px 0; border-bottom: 1px solid rgba(255,255,255,0.06); }
.alt:last-child { border-bottom: none; }
.name { color: #f4f4fb; font-weight: 600; }
.reason { color: #8b8ba7; font-size: 0.82rem; }
.score { color: #cbbfff; font-weight: 600; }
</style>
"""
st.markdown(CSS, unsafe_allow_html=True)


def card(content):
    st.markdown(f'<div class="card">{content}</div>', unsafe_allow_html=True)


@st.cache_data(show_spinner=False)
def cached_explanation(facts, all_names):
    # Errors are not cached, so a failed call can be retried.
    return explain(facts, tuple(all_names))


players = load_prospects(DATA_PATH)
problems = validate(players)
if problems:
    st.error("Data problems: " + "; ".join(problems))
    st.stop()

names = sorted(p["name"] for p in players)
all_names = [p["name"] for p in players]
complete, incomplete = split_complete(players)
max_rank = max(p["espn_rank"] for p in players)

with st.sidebar:
    st.markdown("### Team details")
    team = st.text_input("Team", placeholder="e.g. San Antonio Spurs")
    pick = st.number_input("Pick number", min_value=1, max_value=60, value=1,
                           help="Shown only. It does not change the ranking.")
    needs = st.multiselect("Positions of need", POSITIONS)
    taken = st.multiselect("Already taken", names)
    run = st.button("Get recommendation", type="primary")

st.markdown('<div class="label">2027 draft board</div>', unsafe_allow_html=True)
st.markdown('<div class="big">Draft Pick Evaluator</div>', unsafe_allow_html=True)
st.markdown('<div class="sub">Ranks prospects against a team\'s needs and shows why.</div>',
            unsafe_allow_html=True)
st.write("")

eligible = [p for p in complete if p["name"] not in taken]
c1, c2, c3 = st.columns(3)
c1.metric("Eligible prospects", len(eligible))
c2.metric("Already taken", len(taken))
c3.metric("Excluded (no BPM)", len(incomplete))

if not run:
    card('<div class="label">Ready</div>'
         '<div class="big">Enter a team\'s needs</div>'
         '<div class="sub">Set the team, pick and positions in the sidebar, '
         'then press Get recommendation.</div>')

elif not needs:
    st.warning("Select at least one position of need.")

else:
    top, alts, excluded, close = recommend(players, needs, exclude=taken)

    if top is None:
        st.info("No eligible prospects left.")
    else:
        score, name, reasons = top
        team_label = html.escape(team) if team else "Your team"
        chips = "".join(f'<span class="chip">{html.escape(r)}</span>' for r in reasons)
        card(f'<div class="label">Recommended for {team_label}, pick {pick}</div>'
             f'<div class="big">{html.escape(name)}</div>'
             f'<div class="sub">Score {score} out of 100</div>'
             f'<div>{chips}</div>')

        if close:
            st.info(f"Close call: the top two are within {CLOSE_CALL_MARGIN} point, "
                    "so the order depends on how much the team's needs count.")

        left, right = st.columns(2)

        with left:
            if alts:
                rows = ""
                for alt_score, alt_name, alt_reasons in alts:
                    rows += (f'<div class="alt"><div>'
                             f'<div class="name">{html.escape(alt_name)}</div>'
                             f'<div class="reason">{html.escape("; ".join(alt_reasons))}</div>'
                             f'</div><div class="score">{alt_score}</div></div>')
            else:
                rows = '<div class="sub">None available.</div>'
            card(f'<div class="label">Alternates</div>{rows}')

        with right:
            ranked = rank_prospects(complete, needs, exclude=taken, max_rank=max_rank)[:5]
            chart = pd.DataFrame({"score": [s for s, _, _ in ranked]},
                                 index=[n for _, n, _ in ranked])
            st.markdown('<div class="label">Top five by score</div>', unsafe_allow_html=True)
            st.bar_chart(chart)

        facts = build_facts(team or "Your team", pick, list(needs), top, alts, excluded, close)

        st.markdown('<div class="label">Explanation (Nemotron, from the facts below only)</div>',
                    unsafe_allow_html=True)
        try:
            with st.spinner("Asking Nemotron..."):
                text = cached_explanation(facts, all_names)
            card(f'<div class="sub">{html.escape(text)}</div>')
        except Exception as e:
            st.warning(f"Explanation withheld: {e}. The facts it was built from are shown below.")

        with st.expander("Facts sent to the model"):
            st.code(facts)

        full = rank_prospects(complete, needs, exclude=taken, max_rank=max_rank)
        pdf_bytes = build_report(team or "Your team", pick, needs, taken,
                                 top, alts, excluded, close, full)
        st.download_button(
            "Download report (PDF)",
            data=pdf_bytes,
            file_name=f"draft_pick_{(team or 'team').replace(' ', '_').lower()}.pdf",
            mime="application/pdf",
        )

    st.caption(
        f"Score = {int(W_RANK * 100)} points for ESPN rank, {int(W_PROD * 100)} for BPM "
        f"(fixed scale {BPM_FLOOR} to {BPM_CEILING}), {int(W_NEED * 100)} for a position of need. "
        "Players without a BPM are excluded."
    )
    if excluded:
        st.caption("Excluded (no BPM recorded): " + ", ".join(excluded))