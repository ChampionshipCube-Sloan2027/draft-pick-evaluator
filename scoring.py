import argparse

from data_loader import load_prospects, validate

# Weights are a documented judgement, not fitted to results. They must sum to 1.
W_RANK = 0.65   # consensus: ESPN rank
W_PROD = 0.30   # production: BPM, on fixed bounds below
W_NEED = 0.05   # fit: plays a position the team needs

assert abs(W_RANK + W_PROD + W_NEED - 1.0) < 1e-9

# Fixed BPM bounds, chosen by judgement. Values outside are clipped.
BPM_FLOOR = -5.0
BPM_CEILING = 8.0

# If the top two scores are this close, the output flags a close call.
CLOSE_CALL_MARGIN = 1.0

DATA_PATH = "data/2027_nba_draft_big_board.csv"


def positions_of(p):
    """'PG/SG' -> {'PG', 'SG'}, so a combo guard counts for either need."""
    return {pos.strip().upper() for pos in p["position"].split("/") if pos.strip()}


def normalise_needs(team_needs):
    """Accepts 'PG', 'PG/SG' or a mix, and returns a set of single position codes."""
    needs = set()
    for entry in team_needs:
        for code in entry.split("/"):
            if code.strip():
                needs.add(code.strip().upper())
    return needs


def split_complete(prospects):
    """Separate prospects with a BPM from those without."""
    complete = [p for p in prospects if p["bpm"] is not None]
    incomplete = [p for p in prospects if p["bpm"] is None]
    return complete, incomplete


def score_prospect(p, needs, max_rank):
    """Return (score out of 100, reasons) for one prospect."""
    # Rank 1 maps to 1.0, the last rank maps to 0.0, across the full board.
    rank_part = (max_rank - p["espn_rank"]) / (max_rank - 1)

    # BPM on fixed bounds, clipped to 0.0 to 1.0.
    prod_part = (p["bpm"] - BPM_FLOOR) / (BPM_CEILING - BPM_FLOOR)
    prod_part = min(max(prod_part, 0.0), 1.0)

    matched = positions_of(p) & needs
    need_part = 1.0 if matched else 0.0

    pts = {
        "rank": 100 * W_RANK * rank_part,
        "production": 100 * W_PROD * prod_part,
        "need": 100 * W_NEED * need_part,
    }
    score = round(sum(pts.values()), 1)

    reasons = [
        f"ESPN rank {p['espn_rank']} ({pts['rank']:.1f} pts)",
        f"BPM {p['bpm']:+.2f} ({pts['production']:.1f} pts)",
    ]
    if matched:
        reasons.append(f"fills {', '.join(sorted(matched))} ({pts['need']:.1f} pts)")
    return score, reasons


def rank_prospects(prospects, team_needs, exclude=(), max_rank=None):
    """Return (score, name, reasons), best first. Ties go to the better ESPN rank."""
    needs = normalise_needs(team_needs)
    if max_rank is None:
        max_rank = max(p["espn_rank"] for p in prospects)

    scored = []
    for p in prospects:
        if p["name"] in exclude:
            continue
        score, reasons = score_prospect(p, needs, max_rank)
        scored.append((score, p["espn_rank"], p["name"], reasons))

    scored.sort(key=lambda x: (-x[0], x[1]))
    return [(score, name, reasons) for score, _, name, reasons in scored]


def recommend(prospects, team_needs, alternates=3, exclude=()):
    complete, incomplete = split_complete(prospects)
    # Rank scale uses the full board, so excluded players don't shift it.
    max_rank = max(p["espn_rank"] for p in prospects)
    ranked = rank_prospects(complete, team_needs, exclude, max_rank=max_rank)
    top = ranked[0] if ranked else None
    alts = ranked[1:alternates + 1]
    excluded = [p["name"] for p in incomplete if p["name"] not in exclude]
    close = len(ranked) > 1 and (ranked[0][0] - ranked[1][0]) < CLOSE_CALL_MARGIN
    return top, alts, excluded, close


def main():
    parser = argparse.ArgumentParser(description="Recommend a draft pick.")
    parser.add_argument("--team", default="Team")
    parser.add_argument("--pick", type=int, default=1, help="shown only; not used in scoring")
    parser.add_argument("--needs", nargs="+", required=True, help="position codes, e.g. PG C or PG/SG")
    parser.add_argument("--taken", nargs="*", default=[], help="names already picked, in quotes")
    args = parser.parse_args()

    players = load_prospects(DATA_PATH)
    problems = validate(players)
    if problems:
        raise SystemExit("Fix data problems first: " + "; ".join(problems))

    top, alts, excluded, close = recommend(players, args.needs, exclude=args.taken)

    print(f"{args.team}, pick {args.pick}")
    print(f"Weights: rank {W_RANK}, production {W_PROD}, need {W_NEED}; BPM bounds {BPM_FLOOR} to {BPM_CEILING}")
    if top is None:
        print("No eligible prospects left.")
    else:
        score, name, reasons = top
        print(f"Recommended: {name} ({score}): {'; '.join(reasons)}")
        for score, name, reasons in alts:
            print(f"Alternate: {name} ({score}): {'; '.join(reasons)}")
        if close:
            print(f"Close call: top two are within {CLOSE_CALL_MARGIN} point, so the order is sensitive to the need weight.")
    if excluded:
        print("Excluded (no BPM recorded): " + ", ".join(excluded))


if __name__ == "__main__":
    main()