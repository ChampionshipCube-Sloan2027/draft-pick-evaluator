import csv
import sys

MISSING = {"", "-", "**", "** **", "n/a", "N/A"}
NUMERIC_FIELDS = ["age", "ppg", "rpg", "apg", "fg_pct", "three_pct", "bpm"]


def _clean_number(raw):
    value = raw.strip().replace("%", "").replace("+", "")
    if value in MISSING:
        return None
    return float(value)


def load_prospects(path):
    """Load a draft-class CSV. Missing values become None."""
    prospects = []
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            p = {k.strip(): (v or "").strip() for k, v in row.items()}
            for field in NUMERIC_FIELDS:
                p[field] = _clean_number(p[field])
            p["espn_rank"] = int(p["espn_rank"])
            prospects.append(p)
    return prospects


def validate(prospects):
    """Return a list of problems. An empty list means the file passed."""
    problems = []

    ranks = [p["espn_rank"] for p in prospects]
    if len(ranks) != len(set(ranks)):
        problems.append("duplicate espn_rank values")

    names = [p["name"] for p in prospects]
    for name in sorted(set(names)):
        if names.count(name) > 1:
            problems.append(f"duplicate name: {name}")

    for p in prospects:
        if p["age"] is None:
            problems.append(f"{p['name']}: missing age")
        if not p["league"]:
            problems.append(f"{p['name']}: missing league")

    return problems


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else "data/2027_nba_draft_big_board.csv"
    players = load_prospects(path)
    issues = validate(players)
    print(f"Loaded {len(players)} prospects from {path}")
    if issues:
        print("Problems:")
        for issue in issues:
            print(" -", issue)
    else:
        print("No problems found.")