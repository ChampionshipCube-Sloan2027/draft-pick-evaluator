"""
Injury body map for the Draft Pick Evaluator.

Shows every injury record for a player exactly as it appears in the CSV, with
no filtering or placeholders. The figure is schematic: each body part is
coloured by the reported status recorded against it.

Colours follow the reported status, not a medical assessment:
    red    - out, ruled out, season-ending, indefinitely unavailable
    yellow - questionable, doubtful, probable, day-to-day, limited
    grey   - any other status, or no record for that part

Left and right refer to the figure as drawn: the left side of the picture is
the figure's left.
"""

import math
import re
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

DEFAULT_CSV = Path(__file__).with_name("player_injuries.csv")

REQUIRED_COLUMNS = [
    "player_name", "body_region", "injury", "status",
    "report_date", "body_view", "source_url", "notes",
]

RED_TERMS = ("out", "ruled out", "season-ending", "season ending", "indefinitely")
YELLOW_TERMS = ("doubtful", "questionable", "probable", "day-to-day", "day to day", "limited")

RED_FILL = "rgba(220,69,69,0.85)"
YELLOW_FILL = "rgba(233,155,34,0.85)"
GREY_FILL = "rgba(120,130,145,0.28)"
RED_LINE = "#dc4545"
YELLOW_LINE = "#e99b22"
GREY_LINE = "#8793a0"


# ---------- geometry helpers (coordinates on a 0-100 height scale) ----------

def _ellipse(cx, cy, rx, ry, n=24):
    return [(cx + rx * math.cos(2 * math.pi * i / n),
             cy + ry * math.sin(2 * math.pi * i / n)) for i in range(n)]


def _rect(cx, cy, w, h):
    return [(cx - w / 2, cy - h / 2), (cx + w / 2, cy - h / 2),
            (cx + w / 2, cy + h / 2), (cx - w / 2, cy + h / 2)]


def _capsule(p1, p2, width, n=8):
    """A thick rounded limb segment from p1 to p2."""
    (x1, y1), (x2, y2) = p1, p2
    r = width / 2
    ang = math.atan2(y2 - y1, x2 - x1)
    cap1 = [(x1 + r * math.cos(ang + math.pi / 2 + math.pi * i / n),
             y1 + r * math.sin(ang + math.pi / 2 + math.pi * i / n)) for i in range(n + 1)]
    cap2 = [(x2 + r * math.cos(ang - math.pi / 2 + math.pi * i / n),
             y2 + r * math.sin(ang - math.pi / 2 + math.pi * i / n)) for i in range(n + 1)]
    return cap1 + cap2


# ---------- body parts ----------

# Limbs appear in both views. Each is drawn once for the left side and mirrored for the right.
LIMB_SHAPES = {
    "shoulder": [_capsule((46, 78), (37, 76), 6.5)],
    "arm": [_capsule((37, 76), (31, 62), 6)],
    "elbow": [_ellipse(30.5, 60, 3.2, 3.2)],
    "wrist": [_capsule((30.5, 58), (26, 48), 5)],
    "hip": [_capsule((46, 46), (43, 43), 8)],
    "thigh": [_capsule((44, 42), (43, 28), 8.5)],
    "knee": [_ellipse(43.5, 26.5, 4.2, 3.2)],
    "calf": [_capsule((43.5, 24), (42.5, 11), 7)],
    "ankle": [_ellipse(42.5, 9.5, 3, 2.4)],
    "foot": [_capsule((41.5, 7), (36, 3.5), 4.5)],
}

# Head and neck appear in both views.
CENTRE_SHAPES = {
    "head": [_ellipse(50, 90, 5.5, 6.5)],
    "neck": [_rect(50, 82.5, 4.5, 4)],
}

# Front-only torso regions.
FRONT_TORSO = {
    "chest": [_rect(50, 70, 18, 12)],
    "ribs": [_rect(50, 64.5, 15, 4)],
    "abdomen": [_rect(50, 55, 14, 9)],
}

# Back-only torso regions.
BACK_TORSO = {
    "upper_back": [_rect(50, 70, 18, 12)],
    "lower_back": [_rect(50, 56, 14, 10)],
}


def _figure_parts(view):
    """Every (region, polygon) pair drawn for one view, in local coordinates."""
    parts = []
    for side, mirror in (("left", False), ("right", True)):
        for part, polygons in LIMB_SHAPES.items():
            for poly in polygons:
                pts = [((100 - x) if mirror else x, y) for x, y in poly]
                parts.append((f"{side}_{part}", pts))
    for region, polygons in CENTRE_SHAPES.items():
        for poly in polygons:
            parts.append((region, poly))
    torso = FRONT_TORSO if view == "front" else BACK_TORSO
    for region, polygons in torso.items():
        for poly in polygons:
            parts.append((region, poly))
    return parts


KNOWN_REGIONS = {r for r, _ in _figure_parts("front")} | {r for r, _ in _figure_parts("back")}


# ---------- status handling ----------

def _has_term(value, term):
    return re.search(r"\b" + re.escape(term) + r"\b", value) is not None


def _severity(status):
    """2 = red, 1 = yellow, 0 = grey. Based on the reported status only."""
    value = str(status or "").strip().lower()
    if any(_has_term(value, t) for t in RED_TERMS):
        return 2
    if any(_has_term(value, t) for t in YELLOW_TERMS):
        return 1
    return 0


def _region_severity(rows):
    """Highest severity per body region, and the records behind each region."""
    severity, records = {}, {}
    for _, row in rows.iterrows():
        region = row["body_region"]
        if not region:
            continue
        severity[region] = max(severity.get(region, 0), _severity(row["status"]))
        label = f"{row['injury'] or 'Injury not specified'} ({row['status'] or 'status not given'})"
        records.setdefault(region, []).append(label)
    return severity, records


# ---------- drawing ----------

def _draw_view(fig, view, offset, severity, records):
    for region, pts in _figure_parts(view):
        level = severity.get(region, 0)
        if level == 2:
            fill, line = RED_FILL, RED_LINE
        elif level == 1:
            fill, line = YELLOW_FILL, YELLOW_LINE
        else:
            fill, line = GREY_FILL, GREY_LINE

        label = region.replace("_", " ").title()
        detail = "<br>".join(records.get(region, ["No record for this part"]))
        fig.add_trace(go.Scatter(
            x=[x + offset for x, _ in pts],
            y=[y for _, y in pts],
            mode="lines",
            fill="toself",
            fillcolor=fill,
            line=dict(color=line, width=1.5),
            hoverinfo="text",
            text=f"<b>{label}</b><br>{detail}",
            showlegend=False,
        ))


def _body_figure(rows):
    severity, records = _region_severity(rows)
    fig = go.Figure()
    _draw_view(fig, "front", 0, severity, records)
    _draw_view(fig, "back", 120, severity, records)
    fig.add_annotation(x=50, y=101, text="FRONT", showarrow=False,
                       font=dict(size=13, color=GREY_LINE))
    fig.add_annotation(x=170, y=101, text="BACK", showarrow=False,
                       font=dict(size=13, color=GREY_LINE))
    fig.update_layout(
        height=520,
        margin=dict(l=8, r=8, t=20, b=8),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        xaxis=dict(visible=False, range=[-5, 230], fixedrange=True),
        yaxis=dict(visible=False, range=[0, 104], fixedrange=True,
                   scaleanchor="x", scaleratio=1),
        hoverlabel=dict(align="left"),
    )
    return fig


# ---------- data loading ----------

def load_injuries(csv_path=DEFAULT_CSV):
    """Load every row exactly as stored. Only the column names and region spelling are normalised."""
    path = Path(csv_path)
    if not path.exists():
        return pd.DataFrame(columns=REQUIRED_COLUMNS), f"Couldn't find {path}."

    try:
        df = pd.read_csv(path, dtype=str).fillna("")
    except Exception as exc:
        return pd.DataFrame(columns=REQUIRED_COLUMNS), f"Couldn't read {path.name}: {exc}"

    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        return pd.DataFrame(columns=REQUIRED_COLUMNS), (
            "The injury file is missing these columns: " + ", ".join(missing)
        )

    for column in REQUIRED_COLUMNS:
        df[column] = df[column].astype(str).str.strip()
    df["body_region"] = df["body_region"].str.lower().str.replace(" ", "_")
    return df, None


# ---------- page section ----------

def render_injury_map(player_name, csv_path=DEFAULT_CSV):
    """Render the injury section for one player inside the app."""
    st.markdown("#### Player health map")
    st.caption(
        "Reported injury information only. This visual does not diagnose injuries or "
        "determine medical severity. Colour shows the reported status."
    )

    df, error = load_injuries(csv_path)
    if error:
        st.warning(error)
        return

    rows = df[df["player_name"].str.casefold() == str(player_name).strip().casefold()]
    if rows.empty:
        st.info(f"No injury records in the file for {player_name}.")
        return

    c1, c2, c3 = st.columns(3)
    c1.metric("Recorded entries", len(rows))
    c2.metric("Entries with a status", int((rows["status"] != "").sum()))
    c3.metric("Entries with a source link", int(rows["source_url"].str.startswith("http").sum()))

    st.plotly_chart(_body_figure(rows), use_container_width=True,
                    config={"displayModeBar": False})

    unknown = sorted({r for r in rows["body_region"] if r} - KNOWN_REGIONS)
    if unknown:
        st.caption("Not drawn on the figure, because the region is not recognised: "
                   + ", ".join(unknown))

    st.markdown(
        '<span style="color:#dc4545">● Red</span> out, ruled out, season-ending, indefinitely '
        '&nbsp;&nbsp; <span style="color:#e99b22">● Yellow</span> questionable, doubtful, '
        'probable, day-to-day, limited &nbsp;&nbsp; <span style="color:#8793a0">● Grey</span> '
        'any other status, or no record',
        unsafe_allow_html=True,
    )

    st.markdown("**All records for this player, as stored**")
    table = rows[REQUIRED_COLUMNS].rename(columns={
        "player_name": "Player",
        "body_region": "Body region",
        "injury": "Reported injury",
        "status": "Reported status",
        "report_date": "Report date",
        "body_view": "Body view",
        "source_url": "Source URL",
        "notes": "Notes",
    })
    st.dataframe(table, use_container_width=True, hide_index=True)