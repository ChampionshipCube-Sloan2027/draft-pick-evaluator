import unicodedata
from datetime import date

from fpdf import FPDF

import scoring

# Column widths in mm, totalling 174 on A4 with 18 mm margins.
TABLE_WIDTHS = [10, 58, 16, 90]
WHY_CHARS = 62


def ascii_safe(text):
    """Strip accents so the built-in PDF fonts can render every name."""
    return unicodedata.normalize("NFKD", str(text)).encode("ascii", "ignore").decode("ascii")


class ReportPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 120, 140)
        self.cell(0, 8, "Draft Pick Evaluator | 2027 draft board", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(30, 30, 30)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 140)
        self.cell(0, 8, f"Page {self.page_no()}. Transparent scoring output, not a validated prediction.",
                  align="C")
        self.set_text_color(30, 30, 30)


def _section(pdf, title):
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(60, 40, 130)
    pdf.cell(0, 9, ascii_safe(title), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(30, 30, 30)


def _para(pdf, text, size=10, bold=False):
    pdf.set_font("Helvetica", "B" if bold else "", size)
    pdf.multi_cell(0, 6, ascii_safe(text), new_x="LMARGIN", new_y="NEXT")


def build_report(team, pick, needs, taken, top, alts, excluded, close, full_ranking):
    """Return the report as PDF bytes. Inputs are the outputs of scoring.recommend."""
    pdf = ReportPDF(format="A4")
    pdf.set_margins(18, 18, 18)
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, ascii_safe(f"{team}, pick {pick}"), new_x="LMARGIN", new_y="NEXT")
    _para(pdf, f"Positions of need: {', '.join(needs)}")
    _para(pdf, f"Already taken: {', '.join(taken) if taken else 'none'}")
    _para(pdf, f"Generated {date.today().strftime('%d %B %Y')}")

    score, name, reasons = top
    _section(pdf, "Recommendation")
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 9, ascii_safe(f"{name}  ({score} out of 100)"), new_x="LMARGIN", new_y="NEXT")
    for r in reasons:
        _para(pdf, "- " + r)
    if close:
        pdf.ln(2)
        _para(pdf, f"Close call: the top two are within {scoring.CLOSE_CALL_MARGIN} point, so the "
                   "order depends on how much the team's needs count.")

    _section(pdf, "Alternates")
    for alt_score, alt_name, alt_reasons in alts:
        _para(pdf, f"{alt_name}  ({alt_score})", size=11, bold=True)
        _para(pdf, "; ".join(alt_reasons), size=9)
        pdf.ln(1)

    _section(pdf, "Full ranking (eligible prospects)")
    headers = ["#", "Prospect", "Score", "Why"]
    pdf.set_font("Helvetica", "B", 9)
    for w, h in zip(TABLE_WIDTHS, headers):
        pdf.cell(w, 7, h, border=1)
    pdf.ln()

    pdf.set_font("Helvetica", "", 8)
    for i, (s, n, rs) in enumerate(full_ranking, start=1):
        why = ascii_safe("; ".join(rs))
        if len(why) > WHY_CHARS:
            why = why[:WHY_CHARS - 3] + "..."
        pdf.cell(TABLE_WIDTHS[0], 6, str(i), border=1)
        pdf.cell(TABLE_WIDTHS[1], 6, ascii_safe(n)[:34], border=1)
        pdf.cell(TABLE_WIDTHS[2], 6, f"{s}", border=1)
        pdf.cell(TABLE_WIDTHS[3], 6, why, border=1)
        pdf.ln()

    _section(pdf, "Method")
    _para(pdf, f"Score out of 100 = {int(scoring.W_RANK * 100)} points for ESPN rank, "
               f"{int(scoring.W_PROD * 100)} for BPM on a fixed scale of {scoring.BPM_FLOOR} to "
               f"{scoring.BPM_CEILING} (values outside are clipped), and "
               f"{int(scoring.W_NEED * 100)} for a position of need.", size=9)
    _para(pdf, "The weights are a documented judgement, not fitted to results. The pick number "
               "is shown for reference and does not change the score.", size=9)
    _para(pdf, "Stats are from each player's 2025-26 season. BPM from different leagues is "
               "treated as comparable, which is a known limitation.", size=9)

    if excluded:
        _section(pdf, "Excluded (no BPM recorded)")
        _para(pdf, ", ".join(excluded), size=9)

    return bytes(pdf.output())