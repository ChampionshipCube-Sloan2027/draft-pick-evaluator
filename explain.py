import argparse
import os

from dotenv import load_dotenv
from openai import OpenAI

import scoring
from data_loader import load_prospects, validate

load_dotenv()

MODEL = "nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B"
BASE_URL = "https://api.tokenfactory.nebius.com/v1/"
MAX_TOKENS = 4000

SYSTEM_PROMPT = (
    "You explain draft recommendations for an NBA front office. "
    "Use only the facts you are given, and copy numbers exactly as written. "
    "Only say a prospect fills a team need if that prospect's facts include 'fills'. "
    "Do not add statistics, awards, injuries, positions, or career outcomes that are not in the facts. "
    "Write three to four sentences. "
    "If the facts say 'Close call: yes', say that the order depends on how much "
    "the team's needs count. "
    "If any prospects are excluded, mention that in one short sentence."
)


def build_facts(team, pick, needs, top, alts, excluded, close):
    """Turn the scoring output into plain facts for the model."""
    lines = [f"Team: {team}", f"Pick: {pick}", f"Team needs: {', '.join(needs)}"]

    score, name, reasons = top
    lines.append(f"Recommended: {name}, score {score} out of 100. " + "; ".join(reasons))

    for alt_score, alt_name, alt_reasons in alts:
        lines.append(f"Alternate: {alt_name}, score {alt_score}. " + "; ".join(alt_reasons))

    lines.append("Close call: yes" if close else "Close call: no")
    if excluded:
        lines.append("Excluded, no BPM recorded: " + ", ".join(excluded))
    return "\n".join(lines)


def explain(facts):
    """Ask Nemotron on Token Factory to explain the recommendation."""
    api_key = os.getenv("NEBIUS_API_KEY")
    if not api_key:
        raise RuntimeError("NEBIUS_API_KEY is not set. Check your .env file.")

    client = OpenAI(base_url=BASE_URL, api_key=api_key)
    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": facts},
        ],
        max_tokens=MAX_TOKENS,
    )
    choice = response.choices[0]
    text = choice.message.content
    if not text or not text.strip():
        raise RuntimeError(
            f"Empty response (finish reason: {choice.finish_reason}). "
            "The model may have used its token budget on reasoning."
        )
    return text.strip()


def main():
    parser = argparse.ArgumentParser(description="Explain a draft recommendation.")
    parser.add_argument("--team", default="Team")
    parser.add_argument("--pick", type=int, default=1)
    parser.add_argument("--needs", nargs="+", required=True)
    parser.add_argument("--taken", nargs="*", default=[])
    args = parser.parse_args()

    players = load_prospects(scoring.DATA_PATH)
    problems = validate(players)
    if problems:
        raise SystemExit("Fix data problems first: " + "; ".join(problems))

    top, alts, excluded, close = scoring.recommend(players, args.needs, exclude=args.taken)
    if top is None:
        raise SystemExit("No eligible prospects left.")

    facts = build_facts(args.team, args.pick, args.needs, top, alts, excluded, close)

    print("FACTS")
    print(facts)
    print()
    print("EXPLANATION")
    try:
        print(explain(facts))
    except Exception as e:
        print(f"Explanation unavailable: {e}")


if __name__ == "__main__":
    main()